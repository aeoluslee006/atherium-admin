export function translate(locale, key, vars = {}) {
  const lang = locale === 'en' ? 'en' : 'ko';
  let text = MESSAGES[lang]?.[key] ?? MESSAGES.ko[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value ?? ''));
  }
  return text;
}
